const PRODUCTS_STORAGE_KEY = "pantaloons_store_products";

export function getStoredProducts(): Product[] {
  if (typeof window === "undefined") return INITIAL_PRODUCTS;
  try {
    const raw = localStorage.getItem(PRODUCTS_STORAGE_KEY);
    if (!raw) {
      localStorage.setItem(PRODUCTS_STORAGE_KEY, JSON.stringify(INITIAL_PRODUCTS));
      return INITIAL_PRODUCTS;
    }
    const parsed = JSON.parse(raw);
    if (!Array.isArray(parsed) || parsed.length === 0) {
      return INITIAL_PRODUCTS;
    }
    return parsed;
  } catch {
    return INITIAL_PRODUCTS;
  }
}

export function saveProduct(product: Omit<Product, "id"> & { id?: string }): Product {
  const current = getStoredProducts();
  let saved: Product;

  if (product.id) {
    saved = { ...product, id: product.id } as Product;
    const index = current.findIndex((p) => p.id === product.id);
    if (index >= 0) {
      current[index] = saved;
    } else {
      current.unshift(saved);
    }
  } else {
    saved = {
      ...product,
      id: `prod-${Date.now().toString(36)}`,
    } as Product;
    current.unshift(saved);
  }

  if (typeof window !== "undefined") {
    localStorage.setItem(PRODUCTS_STORAGE_KEY, JSON.stringify(current));
  }
  return saved;
}

export function deleteProduct(id: string): Product[] {
  const current = getStoredProducts();
  const updated = current.filter((p) => p.id !== id);
  if (typeof window !== "undefined") {
    localStorage.setItem(PRODUCTS_STORAGE_KEY, JSON.stringify(updated));
  }
  return updated;
}

export function toggleProductStock(id: string): Product[] {
  const current = getStoredProducts();
  const updated = current.map((p) => (p.id === id ? { ...p, inStock: !p.inStock } : p));
  if (typeof window !== "undefined") {
    localStorage.setItem(PRODUCTS_STORAGE_KEY, JSON.stringify(updated));
  }
  return updated;
}

export function resetProductsToDefault(): Product[] {
  if (typeof window !== "undefined") {
    localStorage.setItem(PRODUCTS_STORAGE_KEY, JSON.stringify(INITIAL_PRODUCTS));
  }
  return INITIAL_PRODUCTS;
}
